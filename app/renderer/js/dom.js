export function icon(name, size) {
  const span = document.createElement('span');
  span.style.display = 'inline-flex';
  span.innerHTML = `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"${size ? ` width="${size}" height="${size}"` : ''}>${ICONS[name] || ''}</svg>`;
  return span.firstElementChild;
}

export function piece(symbol) {
  // symbol: 'wk' ... 'bp' ; the sprite is injected once in index.html
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 40 40');
  const use = document.createElementNS('http://www.w3.org/2000/svg', 'use');
  use.setAttribute('href', `#${symbol}`);
  svg.append(use);
  return svg;
}

export function clamp(value, low, high) { return Math.min(high, Math.max(low, value)); }
